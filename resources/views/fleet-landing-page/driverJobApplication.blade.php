<script>
  document.getElementById('driverJobApplicationForm').addEventListener('submit', async function(e) {
    e.preventDefault();

    const form = e.target;
    const formData = new FormData(form);
    const messageDiv = document.getElementById('formMessage');
    messageDiv.textContent = '';
    messageDiv.style.color = '';

    try {
      const response = await fetch('{{ url("send-driver-job-application") }}', {
        method: 'POST',
        headers: {
          'X-CSRF-TOKEN': '{{ csrf_token() }}'
        },
        body: formData
      });

      const data = await response.json();

      if (data.statusCode === 200) {
        messageDiv.style.color = 'green';
        messageDiv.textContent = data.message || 'تم ارسال الطلب بنجاح';
        form.reset();

      } else {
        messageDiv.style.color = 'red';
        messageDiv.textContent = data.message || 'حدث خطأ أثناء ارسال الطلب';
      }
    } catch (error) {
      messageDiv.style.color = 'red';
      messageDiv.textContent = 'فشل الاتصال بالخادم. حاول مرة أخرى.';
      console.error(error);
    }
  });
</script>



